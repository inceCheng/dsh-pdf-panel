/**
 * Build the standalone viewer lab page.
 *
 * Bundles the real `src/client/pdf/index.tsx` chunk (React included, PDF.js
 * inlined) into `lab/dist/bundle.js` for a plain HTML page. The plugin build's
 * `dsh-pdf-assets` alias is reproduced here from the installed pdfjs-dist so the
 * chunk behaves exactly as it does inside DSH; nothing else is mocked.
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const labDir = dirname(fileURLToPath(import.meta.url))
const pluginRoot = resolve(labDir, '..')
const distDir = join(labDir, 'dist')
const workDir = join(labDir, '.build')
const require = createRequire(join(pluginRoot, 'package.json'))
const labRequire = createRequire(join(labDir, 'package.json'))
const pdfjsRoot = dirname(require.resolve('pdfjs-dist/package.json'))

/**
 * Resolve every React import to the lab's single copy: the plugin's sources
 * resolve `react` from the plugin's node_modules (external in the real build),
 * and two React instances would break hooks in the browser.
 */
const reactAliases = {
  react: labRequire.resolve('react'),
  'react/jsx-runtime': labRequire.resolve('react/jsx-runtime'),
  'react/jsx-dev-runtime': labRequire.resolve('react/jsx-dev-runtime'),
  'react-dom': labRequire.resolve('react-dom'),
  'react-dom/client': labRequire.resolve('react-dom/client'),
}

const PDF_ASSET_KINDS = [['cMapUrl', 'cmaps'], ['standardFontDataUrl', 'standard_fonts'], ['wasmUrl', 'wasm']]

/** Mirror of the plugin build's generated `dsh-pdf-assets` module. */
function generatePdfModule() {
  mkdirSync(workDir, { recursive: true })
  const file = join(workDir, 'pdf-assets.generated.ts')
  const worker = readFileSync(join(pdfjsRoot, 'build/pdf.worker.min.mjs'), 'utf8')
  const pdfAssets = Object.fromEntries(PDF_ASSET_KINDS.map(([kind, directory]) => [
    kind,
    Object.fromEntries(readdirSync(join(pdfjsRoot, directory)).sort()
      .filter(name => !name.startsWith('LICENSE'))
      .map(name => [name, readFileSync(join(pdfjsRoot, directory, name)).toString('base64')])),
  ]))
  writeFileSync(file, [
    '/** Generated by lab/build.mjs — mirror of the plugin build. */',
    `export const workerSource = ${JSON.stringify(worker)}`,
    `export const pdfAssets = ${JSON.stringify(pdfAssets)} as const`,
    '',
  ].join('\n'), 'utf8')
  return file
}

const html = `<!doctype html>
<html lang="zh">
<head>
<meta charset="utf-8" />
<link rel="icon" href="data:," />
<title>dsh-pdf-panel viewer lab</title>
<style>
  html, body { height: 100%; margin: 0; background: #dfe1e5;
    font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", "PingFang SC", sans-serif; }
  body { display: flex; align-items: center; justify-content: center; }
  /* Simulates the right-sidebar box the DSH panel gives the viewer. */
  #frame { display: flex; flex-direction: column; width: 720px; height: 860px;
    border: 1px solid #b9bcc2; border-radius: 10px; overflow: hidden; background: #fff;
    box-shadow: 0 12px 40px rgba(15, 23, 42, 0.22); }
  #root { flex: 1; min-height: 0; }
</style>
</head>
<body>
<div id="frame"><div id="root"></div></div>
<script>
  (() => {
    const width = Number(new URLSearchParams(location.search).get('w'))
    if (Number.isFinite(width) && width > 320) {
      document.getElementById('frame').style.width = width + 'px'
    }
  })()
</script>
<script src="./bundle.js"></script>
</body>
</html>
`

async function main() {
  rmSync(distDir, { recursive: true, force: true })
  mkdirSync(distDir, { recursive: true })
  const generated = generatePdfModule()
  await build({
    entryPoints: [join(labDir, 'entry.tsx')],
    outfile: join(distDir, 'bundle.js'),
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['chrome120'],
    jsx: 'automatic',
    loader: { '.css': 'text' },
    alias: { 'dsh-pdf-assets': generated, ...reactAliases },
    minify: true,
    legalComments: 'none',
    define: { 'process.env.NODE_ENV': '"production"' },
    logLevel: 'warning',
  })
  writeFileSync(join(distDir, 'index.html'), html, 'utf8')
  console.log('[lab] built dist/index.html + dist/bundle.js')
}

await main()
