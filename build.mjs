/**
 * Build the dsh-pdf-panel client halves for the DSH Web module loader.
 *
 * The loader serves each client plugin as a bundle whose script calls
 * `window.__ModuleLoader__.load({ id, factory })`; a package may split heavy
 * code into a lazy chunk (`chunk: '<file>'`) that the main bundle requests with
 * `require.async('./<file>')`. This script produces:
 *
 *   lib/index.js        host Loader entry (hand-written, not built here)
 *   lib/client.js       main client bundle (plugin wiring + panel shell)
 *   lib/client.pdf.js   lazy PDF viewer chunk (PDF.js + inlined PDF.js assets)
 *
 * Adding a dependency to the emitted bundle: declare it in EXTERNALS to use the
 * shell's platform module table, or leave it unlisted so esbuild inlines it.
 */
import { createRequire } from 'node:module'
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
const libDir = join(root, 'lib')
const workDir = join(root, '.build')

/** Modules the Web shell's frozen platform table already provides (never bundled). */
const EXTERNALS = [
  'react',
  'react/jsx-runtime',
  'react-dom',
  '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-slots',
  '@deepseek-ai/dsh-client-store',
]

const PDFJS_ROOT = dirname(require.resolve('pdfjs-dist/package.json'))
/** PDF.js data directories shipped as same-version base64 inside the chunk. */
const PDF_ASSET_KINDS = /** @type {const} */ (['cmaps', 'standard_fonts', 'wasm'])
const PDF_ASSET_OPTION = { cmaps: 'cMapUrl', standard_fonts: 'standardFontDataUrl', wasm: 'wasmUrl' }

function readPdfAssets() {
  const assets = {}
  for (const kind of PDF_ASSET_KINDS) {
    const directory = join(PDFJS_ROOT, kind)
    const files = {}
    for (const name of readdirSync(directory).sort()) {
      if (name.startsWith('LICENSE')) continue
      files[name] = readFileSync(join(directory, name)).toString('base64')
    }
    assets[PDF_ASSET_OPTION[kind]] = files
  }
  return assets
}

function pdfLicenseBanner() {
  const license = readFileSync(join(PDFJS_ROOT, 'LICENSE'), 'utf8').trimEnd()
  return ['//! Bundled PDF.js runtime and data — Apache License 2.0', ...license.split('\n').map(line => `// ${line}`)].join('\n')
}

function generatePdfModule() {
  mkdirSync(workDir, { recursive: true })
  const file = join(workDir, 'pdf-assets.generated.ts')
  const worker = readFileSync(join(PDFJS_ROOT, 'build/pdf.worker.min.mjs'), 'utf8')
  const assets = readPdfAssets()
  writeFileSync(file, [
    '/** Generated by build.mjs — do not edit. Same-version PDF.js worker source and data. */',
    `export const workerSource = ${JSON.stringify(worker)}`,
    `export const pdfAssets = ${JSON.stringify(assets)} as const`,
    '',
  ].join('\n'), 'utf8')
  return file
}

/** The lazy chunk name both the loader registration and require.async agree on. */
const PDF_CHUNK = 'client.pdf.js'

function wrapBundle({ id, chunk, code }) {
  return `window.__ModuleLoader__.load({
\tid: ${JSON.stringify(id)},
${chunk === undefined ? '' : `\tchunk: ${JSON.stringify(chunk)},\n`}\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
${code}
\t\treturn module.exports;
\t}
});
`
}

const commonOptions = {
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['chrome120'],
  jsx: 'automatic',
  loader: { '.css': 'text' },
  external: EXTERNALS,
  minify: true,
  legalComments: 'none',
  logLevel: 'warning',
  define: { 'process.env.NODE_ENV': '"production"' },
}

async function bundle(entry, generatedPdfModule) {
  const result = await build({
    ...commonOptions,
    entryPoints: [join(root, entry)],
    alias: { 'dsh-pdf-assets': generatedPdfModule },
    write: false,
  })
  const output = result.outputFiles?.[0]
  if (output === undefined) throw new Error(`esbuild produced no output for ${entry}`)
  return output.text
}

async function main() {
  rmSync(libDir, { recursive: true, force: true })
  mkdirSync(libDir, { recursive: true })
  const generatedPdfModule = generatePdfModule()

  const [mainCode, pdfCode] = await Promise.all([
    bundle('src/client/index.tsx', generatedPdfModule),
    bundle('src/client/pdf/index.tsx', generatedPdfModule),
  ])

  writeFileSync(join(libDir, 'client.js'), wrapBundle({ id: pkg.name, code: mainCode }), 'utf8')
  writeFileSync(join(libDir, PDF_CHUNK), `${pdfLicenseBanner()}\n${wrapBundle({ id: pkg.name, chunk: PDF_CHUNK, code: pdfCode })}`, 'utf8')
  writeFileSync(join(libDir, 'index.js'), readFileSync(join(root, 'src/host/index.js'), 'utf8'))
  console.log(`[dsh-pdf-panel] built ${(mainCode.length / 1024).toFixed(0)} KiB client + ${(pdfCode.length / 1048576).toFixed(1)} MiB pdf chunk`)
}

await main()
